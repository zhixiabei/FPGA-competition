"""Recreate the frozen hand7 UART bundle from its quantized coefficients."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import struct
import zlib
from handfixed_math import align
ROOT=Path(__file__).resolve().parents[1]
MODEL_BASE=12*1024*1024

def emit_rom(ops,out,crc,model_bytes):
    text=['// Generated by export_handfixed_fpga.py; byte-addressed DDR.','module handfixed_program(input wire [4:0] operation,input wire [2:0] group,',
          'output reg [383:0] descriptor);','always @* begin descriptor=0; case(operation)']
    # byte offsets: kind,relu,k,s,p,0,cin16,cout16,iw,ih,ow,oh,srcplane16,dstplane16,
    # src32,dst32,weights32,coeff32,inputwords16,terms16,area16,groupdst32.
    for op in ops:
        text.append(f"5'd{op['index']}:begin case(group)")
        groups=op.get('groups',[[0,0]])
        for g,(w,c) in enumerate(groups):
            d=struct.pack('<6BHH4BHH4I',op['kind'],int(op['relu']),op['kernel'],op['stride'],op['padding'],0,
                          op['cin'],op['cout'],op['iw'],op['ih'],op['ow'],op['oh'],op['src_plane'],op['dst_plane'],op['src'],op['dst'],w,c)
            d+=struct.pack('<HHHI',op['cin']*op['src_plane']//8,
                           op['cin']*op['kernel']**2,op['ow']*op['oh'],
                           op['dst']+g*24*op['dst_plane']*2)
            d+=bytes(48-len(d))
            text.append(f"3'd{g}:descriptor=384'h{d[::-1].hex()};")
        text+=['default:descriptor=0;endcase end']
    text+=['default:descriptor=0;endcase end','endmodule']
    (out/'handfixed_program.v').write_text('\n'.join(text)+'\n',encoding='utf8')
    config=f'''// Generated; a matching model CRC is required before inference.
module handfixed_config(output wire [31:0] model_base,model_bytes,model_crc32,
output wire [15:0] roi_x,roi_y,roi_side);
assign model_base=32'h{MODEL_BASE:08x};
assign model_bytes=32'h{model_bytes:08x};
assign model_crc32=32'h{crc:08x};
assign roi_x=16'd400;
assign roi_y=16'd120;
assign roi_side=16'd480;
endmodule
'''
    (out/'handfixed_config.v').write_text(config,encoding='utf8')


def export(manifest, output):
    config=json.loads(manifest.read_text(encoding='utf-8-sig'))
    if config['format']!='HFIXCNN1' or config['roi']!=[400,120,480]:
        raise ValueError('Expected the retained fixed-ROI hand7 manifest')
    ops=copy.deepcopy(config['operations'])
    blob=bytearray(256)
    blob[:8]=b'HFIXCNN1'
    for op in ops:
        if op['kind']==1: continue
        for group,(w,c) in enumerate(op['groups']):
            blob.extend(bytes(align(len(blob))-len(blob)))
            assert MODEL_BASE+len(blob)==w
            terms=op['cin']*op['kernel']**2
            for term in range(terms):
                tile=bytearray(32)
                for lane in range(min(24,op['cout']-group*24)):
                    tile[lane]=op['weights'][group*24+lane][term]&255
                blob.extend(tile)
            assert MODEL_BASE+len(blob)==c
            for lane in range(24):
                oc=group*24+lane
                bias,shift=(op['biases'][oc],op['shifts'][oc]) if oc<op['cout'] else (0,0)
                blob.extend((bias&((1<<40)-1)).to_bytes(5,'little')+bytes([shift,0,0]))
    blob.extend(bytes(align(len(blob),256)-len(blob)))
    digest=hashlib.sha256(blob).hexdigest()
    assert digest==config['model_sha256']
    assert f'{zlib.crc32(blob):08x}'==config['crc32']
    output.mkdir(parents=True,exist_ok=False)
    (output/'model.bin').write_bytes(blob)
    (output/'model.hex').write_text(''.join(f'{int.from_bytes(blob[i:i+16],"little"):032x}\n' for i in range(0,len(blob),16)),encoding='ascii')
    (output/'model.json').write_text(json.dumps(config,indent=2),encoding='utf-8')
    emit_rom(ops,output,zlib.crc32(blob),len(blob))
    print(json.dumps(dict(bytes=len(blob),sha256=digest,output=str(output)),indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--manifest',type=Path,default=ROOT/'build/gesture/weights/model.json')
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args()
    export(a.manifest,a.output)
